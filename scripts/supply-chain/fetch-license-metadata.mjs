#!/usr/bin/env node
// =============================================================================
// One-shot dev fetcher for `scripts/supply-chain/license-data.json`.
//
// The SBOM generator must be offline-deterministic, but license metadata lives
// in the public registries. This tool fetches it ONCE per lockfile change from
//   * registry.npmjs.org/<package>/<version>   → `license`
//   * crates.io/api/v1/crates/<name>/<version> → `license` (SPDX expression)
// into a committed, reviewable cache that generation and the license
// inventory then consume without network access.
//
// Rules:
//   * every lockfile entry MUST produce a value ("UNKNOWN" when the registry
//     genuinely has none); a fetch that fails after retries aborts non-zero
//     so no partial cache is ever committed;
//   * output is key-sorted JSON with a fixed shape → diffable and stable;
//   * no credentials, no private paths — public registry metadata only.
//
// Usage:
//   node scripts/supply-chain/fetch-license-metadata.mjs \
//     [--repo-root .] [--out scripts/supply-chain/license-data.json]
// =============================================================================
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { parseCargoLock, parsePnpmLock } from "./lib/lockfiles.mjs";

function arg(name) {
  for (let i = process.argv.length - 1; i >= 0; i -= 1) {
    if (process.argv[i] === `--${name}`) return process.argv[i + 1] ?? null;
  }
  return null;
}

const repoRoot = resolve(arg("repo-root") ?? ".");
const outPath = resolve(arg("out") ?? join(repoRoot, "scripts/supply-chain/license-data.json"));

function fail(message) {
  console.error(`fetch-license-metadata: FAIL — ${message}`);
  process.exit(1);
}

const UA = "promptvault-lite-supply-chain (https://github.com/Mueller-Systems-Lab/promptvault-lite)";

async function fetchJson(url, { cratesIo = false } = {}) {
  const headers = { "User-Agent": UA, Accept: "application/json" };
  if (cratesIo) headers["User-Agent"] = `${UA} license-inventory/1.0`;
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      const res = await fetch(url, { headers });
      if (res.status === 404) return { notFound: true };
      if (res.status === 429 || res.status >= 500) throw new Error(`HTTP ${res.status}`);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.json();
    } catch (e) {
      if (attempt === 3) throw new Error(`${url}: ${e.message}`);
      await new Promise((r) => setTimeout(r, 400 * attempt));
    }
  }
}

/** Run tasks with bounded concurrency, reporting progress. */
async function pool(items, limit, worker) {
  const results = new Array(items.length);
  let next = 0;
  let done = 0;
  async function lane() {
    while (next < items.length) {
      const i = next++;
      results[i] = await worker(items[i], i);
      done += 1;
      if (done % 250 === 0) console.error(`  … ${done}/${items.length}`);
    }
  }
  await Promise.all(Array.from({ length: limit }, lane));
  return results;
}

const pnpm = parsePnpmLock(readFileSync(join(repoRoot, "pnpm-lock.yaml"), "utf8"));
const cargo = parseCargoLock(readFileSync(join(repoRoot, "Cargo.lock"), "utf8"));

const npmIds = [...pnpm.packages.keys()].sort();
const cargoIds = cargo.map((c) => `${c.name}@${c.version}`).sort();
console.error(`fetching license metadata: ${npmIds.length} npm, ${cargoIds.length} cargo entries`);

const npmEntries = await pool(npmIds, 10, async (id) => {
  const [name, ...rest] = id.split("@"); // scoped: rest rejoins below
  const at = id.lastIndexOf("@");
  const pkgName = id.slice(0, at);
  const version = id.slice(at + 1);
  void name;
  void rest;
  try {
    const doc = await fetchJson(
      `https://registry.npmjs.org/${encodeURIComponent(pkgName)}/${version}`,
    );
    if (doc.notFound) return [id, "UNKNOWN"];
    const license = doc.license ?? doc.licenses?.[0]?.type ?? "UNKNOWN";
    return [id, typeof license === "string" ? license : "UNKNOWN"];
  } catch (e) {
    fail(`npm ${id}: ${e.message}`);
  }
});

const cargoEntries = await pool(cargoIds, 4, async (id) => {
  const at = id.lastIndexOf("@");
  const name = id.slice(0, at);
  const version = id.slice(at + 1);
  try {
    const doc = await fetchJson(`https://crates.io/api/v1/crates/${name}/${version}`, {
      cratesIo: true,
    });
    if (doc.notFound) return [id, "UNKNOWN"];
    const license = doc.version?.license ?? "UNKNOWN";
    return [id, typeof license === "string" && license.length > 0 ? license : "UNKNOWN"];
  } catch (e) {
    fail(`cargo ${id}: ${e.message}`);
  }
});

const doc = {
  _comment:
    "Generated by scripts/supply-chain/fetch-license-metadata.mjs from the public npm/crates.io registries. " +
    "Regenerate after every lockfile change: node scripts/supply-chain/fetch-license-metadata.mjs && node scripts/supply-chain/license-inventory.mjs --out docs/supply-chain/license-inventory.md",
  _pnpm_lock_sha256: createHash("sha256")
    .update(readFileSync(join(repoRoot, "pnpm-lock.yaml")))
    .digest("hex"),
  _cargo_lock_sha256: createHash("sha256")
    .update(readFileSync(join(repoRoot, "Cargo.lock")))
    .digest("hex"),
  npm: Object.fromEntries(npmEntries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))),
  cargo: Object.fromEntries(cargoEntries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))),
};

writeFileSync(outPath, `${JSON.stringify(doc, null, 2)}\n`);
const unknown =
  Object.values(doc.npm).filter((v) => v === "UNKNOWN").length +
  Object.values(doc.cargo).filter((v) => v === "UNKNOWN").length;
console.error(
  `wrote ${outPath}: ${Object.keys(doc.npm).length} npm + ${Object.keys(doc.cargo).length} cargo entries (${unknown} UNKNOWN)`,
);
